def load():
    printed = io.open(os.path.join(HERE, "exam.html"), encoding="utf-8").read()
    idx = io.open(os.path.join(HERE, "index.html"), encoding="utf-8").read()
    start = idx.index("const BOOKLET=[")
    end = idx.index("const APPENDIX")
    return printed, idx[start:end]


def main():
    printed, site = load()
    rows, gaps = [], 0
    for label, keys in ITEMS.items():
        a = any(k in printed for k in keys)
        b = any(k in site for k in keys)
        rows.append((label, a, b))
        if a != b:
            gaps += 1

    width = max(len(r[0]) for r in rows) + 2
    print("%-*s %-10s %s" % (width, "פריט", "להדפסה", "באתר"))
    print("─" * (width + 20))
    for label, a, b in rows:
        flag = "" if a == b else "   ←"
        print("%-*s %-10s %s%s" % (width, label, "✔" if a else "✘",
                                   "✔" if b else "✘", flag))

    print()
    if gaps:
        print("%d פריטים מופיעים באחת ולא בשנייה." % gaps)
        print("בדקו בעיניים לפני שמתקנים — ייתכן שזה רק ניסוח אחר.")
    else:
        print("שתי החוברות מכסות את אותם פריטים.")
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
